-- Mix toward an accent without assuming a dark or light background.
local function blend(foreground, background, amount)
  assert(amount >= 0 and amount <= 1, "Blend amount must be between 0 and 1")
  local channels = {}
  for offset = 2, 6, 2 do
    local fg = assert(tonumber(foreground:sub(offset, offset + 1), 16), "Invalid foreground RGB")
    local bg = assert(tonumber(background:sub(offset, offset + 1), 16), "Invalid background RGB")
    channels[#channels + 1] = string.format("%02x", math.floor(fg * amount + bg * (1 - amount) + 0.5))
  end
  return "#" .. table.concat(channels)
end

